#!/usr/bin/env node
/**
 * Embeds a signed .shortcut file into the Worker as a base64 module.
 *
 * Wrangler can import binary files as data modules, but that machinery is not wired into
 * the vitest pool, so the same import would work in production and fail in tests. A
 * generated module works identically everywhere.
 *
 *   node scripts/embed-shortcut.mjs ../shortcut/dist/SMSCodeBridge.signed.shortcut
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/shortcut-asset.ts");

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/embed-shortcut.mjs <signed.shortcut>");
  process.exit(1);
}

const bytes = readFileSync(resolve(process.cwd(), input));

// A signed shortcut is an Apple encrypted archive ("AEA"); an unsigned one is a plist
// starting with "bplist00" or "<?xml". Serving an unsigned file means every user gets an
// import failure, so refuse rather than ship it.
const head = bytes.subarray(0, 8).toString("binary");
if (head.startsWith("bplist") || head.startsWith("<?xml")) {
  console.error("Refusing to embed an UNSIGNED shortcut — iOS 15+ will not import it.");
  console.error("Sign it first:  shortcuts sign --mode anyone -i in.shortcut -o out.shortcut");
  process.exit(1);
}

writeFileSync(
  out,
  `// GENERATED by scripts/embed-shortcut.mjs. Do not edit by hand.
// Source: ${input}
// Bytes: ${bytes.length}
export const SHORTCUT_BASE64 =
  "${bytes.toString("base64")}";
`,
);

console.log(`Embedded ${bytes.length} bytes into src/shortcut-asset.ts`);
